    @npc_io.cached_property
    def stim_running_edges(
        self,
    ) -> tuple[npt.NDArray[np.floating], npt.NDArray[np.floating]]:
        """Rising edges and falling edges on stim_running line, filtered for
        erroneous events and guaranteed to be of equal length.

        - excludes falling edges alone at start, and rising edges alone at end
        - excludes rising+falling pairs that contain exactly one vsync events:
            we have one session (DRpilot_726088_20240618) where a stim was cancelled
            immediately after starting and has no data, but it has a short stim
            running block which causes problems
        """
        stim_running_rising_edges = self.get_rising_edges(
            "stim_running", units="seconds"
        )
        stim_running_falling_edges = self.get_falling_edges(
            "stim_running", units="seconds"
        )

        if any(stim_running_rising_edges) and any(stim_running_falling_edges):
            if stim_running_rising_edges[0] > stim_running_falling_edges[0]:
                stim_running_falling_edges = stim_running_falling_edges[1:]
            if stim_running_falling_edges[-1] < stim_running_rising_edges[-1]:
                stim_running_falling_edges = np.concatenate(
                    [stim_running_falling_edges, [self.total_seconds]]
                )
        assert len(stim_running_rising_edges) == len(stim_running_falling_edges)
        vsyncs = self.get_falling_edges("vsync_stim", units="seconds")
        idx_for_removal = []
        for idx, (on, off) in enumerate(
            zip(stim_running_rising_edges, stim_running_falling_edges, strict=False)
        ):
            if (s := vsyncs[(vsyncs >= on) & (vsyncs <= off)].size) == 1:
                # keeping this strict for now to only affect one session
                logger.warning(
                    f"stim_running block [{on:.2f}:{off:.2f}] has {s} vsync(s)"
                    " - excluding from analysis"
                )
                idx_for_removal.append(idx)
        stim_running_rising_edges = np.delete(
            stim_running_rising_edges, idx_for_removal
        )
        stim_running_falling_edges = np.delete(
            stim_running_falling_edges, idx_for_removal
        )
        return stim_running_rising_edges, stim_running_falling_edges

    def filter_on_stim_running(
        self,
        data: npt.NDArray[np.floating],
        end_padding: float = 0,
    ) -> npt.NDArray[np.floating]:
        """Filter data to only include times when stim_running is high.

        Data must be in seconds relative to first sample.
        - end_padding extends the stim_running off edge in each block, in order to capture delayed presentation of frames.
        """
        if self.stim_running_edges[0].size == 0:
            return data
        mask = [False] * len(data)
        for on, off in zip(*self.stim_running_edges, strict=False):
            mask |= (data >= on) & (data <= off + end_padding)

        return data[mask]

    def divide_into_stim_running_blocks(
        self,
        data: npt.NDArray[np.floating],
        end_padding: float = 0,
    ) -> tuple[npt.NDArray[np.floating], ...]:
        """Divide data into blocks corresponding to stim_running being high.

        Data must be in seconds relative to first sample.
        - end_padding extends the stim_running off edge in each block, in order to capture delayed presentation of frames.

        """
        if self.stim_running_edges[0].size == 0:
            return (data,)
        blocks = []
        for on, off in zip(*self.stim_running_edges, strict=False):
            blocks.append(data[(data >= on) & (data <= off + end_padding)])

        return tuple(blocks)

    @npc_io.cached_property
    def invalid_intervals(self) -> tuple[tuple[float, float], ...]:
        """(start, stop) times in seconds of each interval of sync data that is a replayed
        copy of a later acquisition buffer. Empty if none are found.

        Events in [start, stop) are not real on any line. The last buffer of each run of
        identical buffers is assumed to be genuine and is not included. See
        `find_replayed_buffers`.
        """
        events = self.get_all_events()
        if self.meta_data["ni_daq"]["counter_bits"] == 32:
            times = events[:, 0]
        else:
            times = self.times
        intervals, buffer_size = find_replayed_buffers(times, events[:, -1])
        result = tuple(
            (a / self.sample_freq, z / self.sample_freq) for a, z in intervals
        )
        if result:
            logger.warning(
                f"{self}: {len(result)} interval(s) of replayed sync data with "
                f"{buffer_size}-sample buffers (all lines invalid): "
                f"{[(round(a, 3), round(z, 3)) for a, z in result]}"
            )
        return result

    @npc_io.cached_property
    def timebase_discontinuities(self) -> tuple[tuple[float, float, float], ...]:
        """(start, stop, shift) in seconds for each interval between consecutive barcode onsets
        that is not a whole number of barcode periods: sync data was dropped (shift < 0) or
        inserted (shift > 0) somewhere in [start, stop], on all lines at once. Events after
        `stop` are shifted by `shift` relative to true time.

        Empty if none are found, or if the file has no barcode line / fewer than 4 usable
        barcodes (in which case nothing can be said: check `has_barcodes`). Barcodes that may be
        truncated by the start/end of the recording, or that overlap `invalid_intervals`, are not
        used. See `find_barcode_discontinuities`.
        """
        if not self.has_barcodes:
            return ()
        result = find_barcode_discontinuities(
            self._get_recorded_edges("barcode_ephys", "rising") / self.sample_freq,
            total_seconds=self.total_seconds,
            invalid_intervals=self.invalid_intervals,
        )
        if result:
            logger.warning(
                f"{self}: {len(result)} timebase discontinuity(ies) from barcode onset intervals "
                f"(all lines affected, events after are shifted): "
                f"{[(round(a, 2), round(z, 2), round(d, 3)) for a, z, d in result]}"
            )
        return result

