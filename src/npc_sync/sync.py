SyncPathOrDataset: TypeAlias = Union[npc_io.PathLike, h5py.File, "SyncDataset"]

OnInvalid: TypeAlias = Literal["raise", "mask", "ignore"]

FIRST_SOUND_ON_SYNC_DATE = datetime.date(2023, 8, 31)
"""Prior to this date, there's no sync line with "sound running" signal, on any rig: need to
use NI-DAQ analog recording on OpenEphys PXI to get sound onset times."""

FIRST_GALVO_ON_SYNC_DATE = datetime.date(2024, 4, 19)
"""Prior to this date, opto experiments using the galvo system did not have a "galvo motor
running" signal, on any rig. A copy of the analog signal may have been recorded on the OpenEphys DAQ."""

REPLAY_SLOT_SAMPLES = 10_000
"""Slot width, in samples, used to fingerprint sync events when looking for replayed
acquisition buffers. Buffer sizes seen so far (50,000 and 10,000 samples) are multiples
of this. Buffer size is not recorded in the sync file metadata."""

REPLAY_MAX_BUFFER_SAMPLES = 50_000
"""Largest acquisition buffer (0.5 s at 100 kHz) considered when looking for replayed
buffers. Identical slots separated by more than this are coincidental matches (e.g. quiet
or periodic stretches of real data) and are ignored."""

BARCODE_MIN_GAP_SEC = 20.0
"""Rising edges on the barcode line separated by more than this start a new barcode.
Barcodes are emitted every ~31 s and last <2 s."""

BARCODE_MAX_DURATION_SEC = 2.0
"""Upper bound on the duration of one barcode (observed 0.68-1.82 s). Used as the margin around
the recording edges (truncated barcodes) and around invalid intervals."""

BARCODE_INTERVAL_TOLERANCE_SEC = 0.010
"""Largest deviation of a barcode onset interval from its per-file median (or an integer
multiple of it, if barcodes were excluded in between) that is still considered regular.
Observed on 6 clean files: <= 0.31 ms."""


def get_sync_data(sync_path_or_data: SyncPathOrDataset) -> SyncDataset:
    """Open a path or file-like object and return a SyncDataset object."""
    if isinstance(sync_path_or_data, SyncDataset):
        return sync_path_or_data
    return SyncDataset(sync_path_or_data)


def get_single_sync_path(
    dir_or_paths: npc_io.PathLike | Iterable[npc_io.PathLike],
    date: (
        str
        | datetime.date
        | datetime.datetime
        | npc_session.DateRecord
        | npc_session.DatetimeRecord
        | None
    ) = None,
) -> upath.UPath:
    """From an iterable of paths, return the one with the expected date and a
    .sync or .h5 extension.

    >>> get_single_sync_path('s3://aind-ephys-data/ecephys_676909_2023-12-14_12-43-11/behavior')
    S3Path('s3://aind-ephys-data/ecephys_676909_2023-12-14_12-43-11/behavior/20231214T124311.h5')
    """
    if isinstance(dir_or_paths, str):
        dir_or_paths = npc_io.from_pathlike(dir_or_paths)
    if not isinstance(dir_or_paths, Iterable):
        if (d := npc_io.from_pathlike(dir_or_paths)).is_dir():
            dir_or_paths = d.iterdir()
        else:
            dir_or_paths = [dir_or_paths]

    if date is not None:
        try:
            date = npc_session.DatetimeRecord(date)
        except ValueError:
            date = npc_session.DateRecord(date)

    sync_files = []
    all_paths: list[upath.UPath] = [npc_io.from_pathlike(p) for p in dir_or_paths]  # type: ignore[arg-type, union-attr]
    for p in all_paths:
        if p.suffix not in (".sync", ".h5"):
            continue
        if date is not None:
            try:
                if isinstance(date, npc_session.DatetimeRecord):
                    file_date: npc_session.DatetimeRecord | npc_session.DateRecord = (
                        npc_session.DatetimeRecord(p.stem)
                    )
                else:
                    file_date = npc_session.DateRecord(p.stem)
            except ValueError:
                continue
            if file_date != date:
                continue
        sync_files.append(p)

    if not len(sync_files) == 1:
        raise ValueError(f"Expected 1 sync file, found {sync_files = }")
    return sync_files[0]


def get_bit(uint_array: npt.NDArray, bit: int) -> npt.NDArray[np.uint8]:
    """
    Returns a bool array for a specific bit in a uint ndarray.

    Parameters
    ----------
    uint_array : (numpy.ndarray)
        The array to extract bits from.
    bit : (int)
        The bit to extract.

    """
    return np.bitwise_and(uint_array, 2**bit).astype(bool).astype(np.uint8)


def _splitmix64(x: npt.NDArray[np.uint64]) -> npt.NDArray[np.uint64]:
    """Vectorized splitmix64 finalizer: scrambles 64-bit integers."""
    x = x.astype(np.uint64, copy=True)
    with np.errstate(over="ignore"):
        x ^= x >> np.uint64(30)
        x *= np.uint64(0xBF58476D1CE4E5B9)
        x ^= x >> np.uint64(27)
        x *= np.uint64(0x94D049BB133111EB)
        x ^= x >> np.uint64(31)
    return x


def find_replayed_buffers(
    times: npt.ArrayLike,
    bits: npt.ArrayLike,
    slot_samples: int = REPLAY_SLOT_SAMPLES,
    max_buffer_samples: int = REPLAY_MAX_BUFFER_SAMPLES,
) -> tuple[tuple[tuple[int, int], ...], int | None]:
    """Find acquisition buffers in a sync event list that are replayed copies of a later
    buffer.

    Some sync files contain runs of consecutive buffers with identical event content on
    every line (same sample times relative to the buffer start, same bit states). The
    copies overwrite real data; the last buffer of each run is assumed to be genuine.

    Method: split events into slots of `slot_samples`, fingerprint each non-empty slot
    by summing a hash of each event's (time relative to slot start, bit state), then find
    slots with identical fingerprints. The most common slot separation between identical
    slots gives the buffer size, so any buffer size that is a multiple of `slot_samples`
    is found. Buffers are assumed to be aligned to sample 0.

    Parameters
    ----------
    times : array of int
        Sample index of each event.
    bits : array of int
        Bit state (all lines) of each event.
    slot_samples : int
        Fingerprint slot width in samples. Must divide the buffer size.
    max_buffer_samples : int
        Identical slots further apart than this are not treated as replays.

    Returns
    -------
    intervals : tuple of (start, stop) sample indices
        Half-open intervals of replayed copies. `stop` is the start of the genuine buffer.
    buffer_size : int or None
        Inferred buffer size in samples, or None if no replay was found.

    Examples
    --------
    >>> rng = np.random.default_rng(0)
    >>> buffer, n_buffers = 50_000, 20
    >>> rel = [np.sort(rng.choice(buffer, 100, replace=False)) for _ in range(n_buffers)]
    >>> state = [rng.integers(0, 2**32, 100) for _ in range(n_buffers)]
    >>> for i in (5, 6, 7):  # buffers 5-7 are copies of buffer 8
    ...     rel[i], state[i] = rel[8], state[8]
    >>> times = np.concatenate([r + i * buffer for i, r in enumerate(rel)])
    >>> find_replayed_buffers(times, np.concatenate(state))
    (((250000, 400000),), 50000)
    >>> find_replayed_buffers(times[times < 250_000], np.concatenate(state)[times < 250_000])
    ((), None)
    """
    times = np.asarray(times).astype(np.int64)
    bits = np.asarray(bits).astype(np.uint64)
    if times.size == 0:
        return (), None
    slot = times // slot_samples
    starts = np.flatnonzero(np.r_[True, slot[1:] != slot[:-1]])  # non-empty slots only
    tokens = ((times - slot * slot_samples).astype(np.uint64) << np.uint64(32)) | (
        bits & np.uint64(0xFFFFFFFF)
    )
    with np.errstate(over="ignore"):
        fingerprints = np.add.reduceat(_splitmix64(tokens), starts)
    slots = slot[starts]
    order = np.lexsort((slots, fingerprints))  # by fingerprint, then slot
    fingerprints, slots = fingerprints[order], slots[order]
    same = fingerprints[1:] == fingerprints[:-1]
    if not same.any():
        return (), None
    earlier = slots[:-1][same]
    lags = slots[1:][same] - earlier
    plausible = lags <= max_buffer_samples // slot_samples
    earlier, lags = earlier[plausible], lags[plausible]
    if lags.size == 0:
        return (), None
    values, counts = np.unique(lags, return_counts=True)
    lag = int(values[np.argmax(counts)])
    if len(values) > 1:
        logger.warning(
            "Identical sync slots found at more than one separation "
            f"(in units of {slot_samples} samples): "
            f"{dict(zip(values.tolist(), counts.tolist(), strict=False))}. Using the most common ({lag})."
        )
    buffer_size = lag * slot_samples
    copies = np.unique(
        earlier[lags == lag] // lag
    )  # buffer index of each replayed copy
    breaks = np.flatnonzero(np.diff(copies) != 1)
    first = copies[np.r_[0, breaks + 1]]
    last = copies[np.r_[breaks, len(copies) - 1]]
    intervals = tuple(
        (int(a * buffer_size), int((z + 1) * buffer_size))
        for a, z in zip(first, last, strict=False)
    )
    return intervals, buffer_size


def find_barcode_discontinuities(
    barcode_rising_edges: npt.ArrayLike,
    total_seconds: float,
    invalid_intervals: Sequence[tuple[float, float]] = (),
    tolerance: float = BARCODE_INTERVAL_TOLERANCE_SEC,
) -> tuple[tuple[float, float, float], ...]:
    """Find intervals between barcode onsets that are not a whole number of barcode periods:
    sync data was dropped (negative shift) or inserted (positive shift) somewhere in between,
    on every line at once.

    Barcodes are generated at a fixed period, so onset intervals are regular to well under 1 ms
    (max 0.31 ms seen). A dropped 0.5 s buffer with no gap in sample numbers shortens one
    interval by exactly 0.5 s and shifts all later events early.

    Only barcodes that can be trusted are used:

    - the first barcode is excluded if it starts within `BARCODE_MAX_DURATION_SEC` of the
      recording start, and the last if it ends (start + max duration) after the recording end:
      either may be truncated
    - barcodes within `BARCODE_MAX_DURATION_SEC` of an invalid (replayed) interval are excluded
      (their edges may be copies, or only partly present)

    Intervals spanning excluded barcodes are compared with the nearest integer multiple of the
    period. Files with fewer than 4 usable barcodes (or no barcode line) return ().

    Returns
    -------
    tuple of (start, stop, shift)
        Seconds. The drop/insertion happened somewhere between consecutive usable barcode onsets
        `start` and `stop`; events at `stop` or later are shifted by `shift` (negative: recorded
        early, i.e. data is missing). Treat [start, stop] as invalid on all lines, and every
        event after it as shifted unless corrected.

    Examples
    --------
    >>> onsets = np.arange(10) * 31.0 + 5.0
    >>> find_barcode_discontinuities(onsets, 400.0)
    ()
    >>> dropped = np.r_[onsets[:5], onsets[5:] - 1.0]  # 1 s dropped before barcode 5
    >>> find_barcode_discontinuities(dropped, 400.0)
    ((129.0, 159.0, -1.0),)

    Truncated first and last barcodes are ignored:
    >>> find_barcode_discontinuities(np.r_[0.5, onsets[1:-1], 398.5], 399.0)
    ()
    """
    on = np.sort(np.asarray(barcode_rising_edges, dtype=float))
    if on.size == 0:
        return ()
    starts = on[np.r_[True, np.diff(on) > BARCODE_MIN_GAP_SEC]]
    keep = (starts >= BARCODE_MAX_DURATION_SEC) & (
        starts + BARCODE_MAX_DURATION_SEC <= total_seconds
    )
    for a, z in invalid_intervals:
        keep &= ~(
            (starts + BARCODE_MAX_DURATION_SEC > a)
            & (starts - BARCODE_MAX_DURATION_SEC < z)
        )
    starts = starts[keep]
    if starts.size < 4:  # need >= 3 intervals for a meaningful median
        return ()
    intervals = np.diff(starts)
    # the shortest intervals are between adjacent usable barcodes; a dropped buffer shortens
    # one by <= a few seconds, so anchor the period on the median of the minimum-multiple ones
    approx = np.min(intervals)
    multiples = np.maximum(np.round(intervals / approx), 1)
    period = float(np.median(intervals[multiples == 1]))
    multiples = np.maximum(np.round(intervals / period), 1)
    deviation = intervals - multiples * period
    return tuple(
        (float(starts[i]), float(starts[i + 1]), float(deviation[i]))
        for i in np.flatnonzero(np.abs(deviation) > tolerance)
    )


def get_sync_line_for_stim_onset(
    waveform_type: (
        str | Literal["sound", "audio", "opto", "galvo", "laser_488", "laser_633"]
    ),
    date: datetime.date | None = None,
) -> int:
    """Return the sync line index for the given waveform type.

    - `opto` currently defaults to laser 488
    """
    if any(label in waveform_type for label in ("aud", "sound")):
        if date and date < FIRST_SOUND_ON_SYNC_DATE:
            raise ValueError(
                f"Sound only recorded on sync since {FIRST_SOUND_ON_SYNC_DATE.isoformat()}: {date = }"
            )
        return 1
    elif any(label in waveform_type for label in ("opto", "488")):
        return 11
    elif "galvo" in waveform_type:
        if date and date < FIRST_GALVO_ON_SYNC_DATE:
            raise ValueError(
                f"Galvo only recorded on sync since {FIRST_GALVO_ON_SYNC_DATE.isoformat()}: {date = }"
            )
        return 9
    elif "633" in waveform_type:
        if date and date < FIRST_GALVO_ON_SYNC_DATE:
            raise ValueError(
                f"Laser 688 only recorded on sync since {FIRST_GALVO_ON_SYNC_DATE.isoformat()}: {date = }"
            )
        return 10
    else:
        raise ValueError(f"Unexpected value: {waveform_type = }")


class SyncDataset:
    """
    A sync dataset.  Contains methods for loading
        and parsing the binary data.

    Parameters
    ----------
    path : str
        Path to HDF5 file.

    Examples
    --------
    >>> dset = SyncDataset('s3://aind-ephys-data/ecephys_676909_2023-12-14_12-43-11/behavior/20231214T124311.h5')
    >>> dset.validate(opto=True, audio=True)

    >>> with SyncDataset('my_h5_file.h5') as d: # doctest: +SKIP
    ...     dset.validate()

    The sync file documentation from MPE can be found at
    sharepoint > Instrumentation > Shared Documents > Sync_line_labels_discussion_2020-01-27-.xlsx  # NOQA E501
    Direct link:
    https://alleninstitute.sharepoint.com/:x:/s/Instrumentation/ES2bi1xJ3E9NupX-zQeXTlYBS2mVVySycfbCQhsD_jPMUw?e=Z9jCwH


    """

    stim_paths: tuple[upath.UPath, ...] | None
    """Deprecated: only used by the deprecated display-time members, which moved to
    npc_stim (pass stim paths to `npc_stim.get_display_times` instead)."""

    patch: SyncPatch | None
    """Corrections to the recorded edges (see `npc_sync.patch.SyncPatch`): replacement edges
    inside `invalid_intervals`, and measured edges removed anywhere (photodiode phantom flicker
    and glitches)."""

    on_invalid: OnInvalid
    """What edge queries do on a line whose data inside `invalid_intervals` is not covered by
    `patch` (a line the patch covers always gets the patch):

    - 'raise' (default): raise `SyncFaultError`
    - 'mask': drop the edges inside the intervals (treat them as unknown; see
      `get_unknown_intervals`)
    - 'ignore': return the recorded edges, copies included (the behaviour before 0.3.2; for
      diagnostics only)
    """

    def __init__(
        self,
        path: npc_io.PathLike | Self,
        stim_paths: Iterable[npc_io.PathLike] | None = None,
        patch: SyncPatch | None = None,
        on_invalid: OnInvalid | None = None,
    ) -> None:
        if isinstance(path, self.__class__):
            self.path = path.path
            self.dfile = path.dfile
            if patch is None and on_invalid is None:  # same view as `path`
                patch, on_invalid = path.patch, path.on_invalid
        else:
            self.path = npc_io.from_pathlike(path)
            self.dfile = self.load(path)
        if stim_paths is None:
            self.stim_paths = None
        else:
            self.stim_paths = tuple(npc_io.from_pathlike(p) for p in stim_paths)
        self.on_invalid = on_invalid or "raise"
        if self.on_invalid not in ("raise", "mask", "ignore"):
            raise ValueError(
                f"on_invalid must be 'raise', 'mask' or 'ignore': got {on_invalid!r}"
            )
        self.patch = patch
        if patch is not None and patch.sync_content_hash != self.content_hash:
            raise ValueError(
                "patch was built for a different sync file (content hash "
                f"{patch.sync_content_hash[:12]}..., this file {self.content_hash[:12]}...)"
            )

    def __repr__(self) -> str:
        return f"{self.__class__.__name__}({self.path.as_posix()})"

    @npc_io.cached_property
    def content_hash(self) -> str:
        """sha256 of the event data and metadata: identifies the recording a `SyncPatch` was
        built for, wherever the file is stored."""
        h = hashlib.sha256()
        h.update(np.ascontiguousarray(self.dfile["data"][()]).tobytes())
        h.update(repr(sorted(self.meta_data.items(), key=lambda kv: kv[0])).encode())
        return h.hexdigest()

    def line_key(self, line: str | int) -> str:
        """Label of a line, or 'bit<n>' if it's unlabelled (the key used in `SyncPatch`)."""
        return line_key(self.line_labels, self._line_to_bit(line))

    def get_unknown_intervals(self, line: str | int) -> tuple[tuple[float, float], ...]:
        """Intervals (seconds) in which events on `line` are unknown: no edges are returned
        there and nothing replaces them. Empty if the file has no invalid intervals or the
        patch reconstructs every interval for this line. Raises like the edge getters if the
        line is neither patched nor masked."""
        if not self.invalid_intervals:
            return ()
        key = self.line_key(line)
        if self.patch is not None and self.patch.covers(key):
            return self.patch.unknown_intervals(key)
        if self.on_invalid == "ignore":
            return ()
        if self.on_invalid == "mask":
            return self._mask_intervals
        raise SyncFaultError(self._invalid_message(key))

    @property
    def _mask_intervals(self) -> tuple[tuple[float, float], ...]:
        """Invalid intervals, starting one sample early: the event at the sample before a copy
        can carry the copy's state (see `npc_sync.patch.build_sync_patch`)."""
        return tuple((a - 1 / self.sample_freq, z) for a, z in self.invalid_intervals)

    def _invalid_message(self, key: str) -> str:
        shown = ", ".join(f"{a:.3f}-{z:.3f} s" for a, z in self.invalid_intervals[:5])
        more = ", ..." if len(self.invalid_intervals) > 5 else ""
        return (
            f"{self}: sync data on all lines is invalid in {len(self.invalid_intervals)} "
            f"replayed interval(s) ({shown}{more}) and no patch covers {key!r}: supply "
            "`patch=` (see npc_sync.patch) or use `on_invalid='mask'`"
        )

    def _apply_invalid_policy(
        self,
        line: str | int,
        kind: Literal["rising", "falling"],
        times_samples: npt.NDArray[Any],
        units: str,
    ) -> tuple[npt.NDArray[Any], npt.NDArray[np.int8]]:
        """Recorded edges (samples) -> edges in `units` after the patch's removals (any file)
        and the invalid-interval policy, plus the per-edge source (see
        `npc_sync.patch.SOURCE_NAMES`)."""
        seconds = units.lower() in ("seconds", "sec", "secs")
        if not seconds and units.lower() != "samples":
            raise ValueError("Only 'samples' or 'seconds' are valid units.")
        fs = self.sample_freq
        if self.patch is not None and self.patch.removed:
            # measured edges the patch removes (e.g. photodiode phantom flicker), in any file
            times_samples = times_samples[
                self.patch.keep_recorded(self.line_key(line), kind, times_samples)
            ]
        sources = np.full(len(times_samples), MEASURED, dtype=np.int8)
        if not self.invalid_intervals:
            return (times_samples / fs if seconds else times_samples), sources
        key = self.line_key(line)
        t = times_samples / fs
        if self.patch is not None and self.patch.covers(key):
            t, sources = self.patch.apply(key, kind, t)
        elif self.on_invalid == "ignore":
            return (times_samples / fs if seconds else times_samples), sources
        elif self.on_invalid == "mask":
            keep = ~in_intervals(t, self._mask_intervals)
            t, sources = t[keep], sources[keep]
        else:
            raise SyncFaultError(self._invalid_message(key))
        if seconds:
            return t, sources
        return np.round(t * fs).astype(np.int64), sources

    def get_edge_sources(
        self, line: str | int, kind: Literal["rising", "falling"]
    ) -> npt.NDArray[np.int8]:
        """Per-edge source (MEASURED=0, INTERPOLATED=1) aligned with `get_rising_edges` or
        `get_falling_edges` for `line`."""
        raw = self._get_recorded_edges(line, kind)
        return self._apply_invalid_policy(line, kind, raw, "samples")[1]

    def _get_recorded_edges(
        self, line: str | int, kind: Literal["rising", "falling"]
    ) -> npt.NDArray[Any]:
        """Edges as recorded (samples), copies included."""
        bit = self._line_to_bit(line)
        changes = self.get_bit_changes(bit)
        return self.get_all_times("samples")[
            np.where(changes == (1 if kind == "rising" else 255))
        ]

    def validate(
        self,
        camstim: bool = True,
        mvr: bool = True,
        barcodes: bool = True,
        licks: bool = False,
        opto: bool = False,
        audio: bool = False,
    ) -> None:
        """
        Check all lines are present and have events.

        - if opto or audio are True, work out which line indices correspond and
          check those too
        """
        if not self.line_labels:
            raise AssertionError("Sync file has no line labels.")

        lines: list[str | int] = []
        if camstim:
            lines.extend(["vsync_stim", "stim_photodiode", "stim_running"])
        if mvr:
            lines.extend(
                [
                    f"{cam}_cam_{suffix}"
                    for cam in ("beh", "eye", "face")
                    for suffix in ("exposing",)
                ]
            )
        if barcodes:
            lines.append("barcode_ephys")
        if licks:
            lines.append("lick_sensor")
        if opto:
            has_laser_633_and_galvo = self.start_time.date() >= FIRST_GALVO_ON_SYNC_DATE
            try:
                self._check_line(a := self.get_line_for_stim_onset("laser_488"))
            except AssertionError:
                if has_laser_633_and_galvo:
                    self._check_line(b := self.get_line_for_stim_onset("laser_633"))
                else:
                    raise AssertionError(
                        f"Sync file has no events on opto lines {a = } or {b = }"
                    ) from None
            if has_laser_633_and_galvo:
                self._check_line(self.get_line_for_stim_onset("galvo"))
        if audio and self.start_time.date() >= FIRST_SOUND_ON_SYNC_DATE:
            lines.append(self.get_line_for_stim_onset("audio"))

        for line in lines:
            self._check_line(line)

        if camstim:
            self._check_camstim_lines()
        logger.info(f"Sync file passed validation for {lines = }")

    def _check_line(self, label_or_index: str | int) -> None:
        """Verify line is present and has events, or raise AssertionError."""
        stats = self.line_stats(label_or_index)
        if stats is None:
            raise AssertionError(f"Sync file has no events on line {label_or_index}")

    def _check_camstim_lines(self) -> None:
        self._check_stim_photodiode()
        self._check_vsyncs()

    def _check_stim_photodiode(self) -> None:
        """Diode flip-rate check, now in `npc_stim.check_stim_photodiode`: skipped with a
        warning if npc_stim isn't installed."""
        try:
            npc_stim = _npc_stim()
        except ImportError:
            logger.warning(
                "npc_stim not installed: skipping photodiode flip-rate check (moved to npc_stim.check_stim_photodiode)"
            )
            return
        npc_stim.check_stim_photodiode(self)

